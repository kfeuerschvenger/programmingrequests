package com.feuerschvenger.codequests.config;

import com.feuerschvenger.codequests.exception.ErrorCode;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.License;
import io.swagger.v3.oas.models.media.ArraySchema;
import io.swagger.v3.oas.models.media.IntegerSchema;
import io.swagger.v3.oas.models.media.ObjectSchema;
import io.swagger.v3.oas.models.media.Schema;
import io.swagger.v3.oas.models.media.StringSchema;
import org.springdoc.core.customizers.OpenApiCustomizer;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.boot.info.BuildProperties;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import java.util.Arrays;
import java.util.List;

/**
 * OpenAPI metadata and the corrections the annotations cannot express. The version comes from the build info generated by Gradle and falls back to {@code dev} when it is absent. The documentation endpoints themselves are enabled only by the {@code dev} profile.
 */
@Configuration
public class SwaggerConfig {

    private static final String PROBLEM_SCHEMA = "ProblemDetail";
    private static final String JSON = "application/json";
    private static final String ANY_TYPE = "*/*";

    @Bean
    public OpenAPI codeQuestsOpenApi(ObjectProvider<BuildProperties> buildProperties) {
        var version = buildProperties.stream().findFirst().map(BuildProperties::getVersion).orElse("dev");
        return new OpenAPI().info(new Info()
                .title("Code Quests API")
                .description("API for submitting programming ideas and voting on them.")
                .version(version)
                .license(new License().name("MIT").url("https://opensource.org/licenses/MIT")));
    }

    /**
     * Fixes three things the generator gets wrong. Allowable values on an integer property are exported as strings, so the vote enums are set here as numbers. Spring's {@code ProblemDetail} is exported as its Java shape, not the body {@code GlobalExceptionHandler} writes, so the schema is replaced with the wire body. Success responses are exported under {@code *&#47;*}, while the API answers {@code application/json}.
     */
    @Bean
    public OpenApiCustomizer contractCustomizer() {
        return openApi -> {
            var schemas = openApi.getComponents().getSchemas();
            integerEnum(schemas.get("VoteRequest"), "value", -1, 1);
            integerEnum(schemas.get("IdeaResponse"), "myVote", -1, 0, 1);
            schemas.put(PROBLEM_SCHEMA, problemDetail());
            openApi.getPaths().values().forEach(path -> path.readOperations().forEach(operation ->
                    operation.getResponses().forEach((code, response) -> {
                        var content = response.getContent();
                        if (code.startsWith("2") && content != null && content.containsKey(ANY_TYPE)) {
                            content.addMediaType(JSON, content.remove(ANY_TYPE));
                        }
                    })));
        };
    }

    @SuppressWarnings({"unchecked", "rawtypes"})
    private static void integerEnum(Schema<?> owner, String property, int... values) {
        Schema<?> target = (Schema<?>) owner.getProperties().get(property);
        target.setEnum((List) Arrays.stream(values).boxed().toList());
    }

    private static Schema<?> problemDetail() {
        var errors = new ArraySchema()
                .description("The failed fields. Present only on validation errors.")
                .items(new ObjectSchema()
                        .addProperty("field", new StringSchema().description("Name of the parameter or body field."))
                        .addProperty("message", new StringSchema().description("Fixed text that says what is wrong. It never repeats the value."))
                        .addRequiredItem("field")
                        .addRequiredItem("message"));
        var code = new StringSchema().description("Stable machine-readable error code.");
        code.setEnum(Arrays.stream(ErrorCode.values()).map(Enum::name).toList());
        var schema = new ObjectSchema();
        schema.description("An RFC 9457 problem. Every error response has this shape.");
        schema.addProperty("type", new StringSchema().format("uri").description("Problem type, about:blank unless a handler sets one."));
        schema.addProperty("title", new StringSchema().description("The HTTP reason phrase."));
        schema.addProperty("status", new IntegerSchema().format("int32").description("The HTTP status code."));
        schema.addProperty("detail", new StringSchema().description("Fixed text for the error code. It never carries request input."));
        schema.addProperty("instance", new StringSchema().format("uri").description("urn:request-id: followed by the request id, which matches the log line."));
        schema.addProperty("code", code);
        schema.addProperty("errors", errors);
        schema.addProperty("retryAfterSeconds", new IntegerSchema().format("int64").description("Whole seconds to wait. Present only on 429, and equal to the Retry-After header."));
        schema.addRequiredItem("status");
        schema.addRequiredItem("code");
        return schema;
    }
}
